import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it } from "vitest";
import redis from "redis";
import { QueryTypes } from "sequelize";
import { Room, RoomUser, type RoomStateFromRedis } from "../../room.js";
import { redisStateToState } from "../../roommanager.js";
import { buildClients, createSubscriber, redisClient } from "../../redisclient.js";
import { conf } from "../../ott-config.js";
import { SqlMusicRoomStore } from "../../music/room-music-storage.js";
import { musicRoomModels } from "../../models/music-room.js";
import { QueueMode } from "ott-common/models/types.js";
import { createFixture, reference, targets } from "./music-fixture.js";

const REDIS_VERSION = /^redis_version:(.+)$/m;

describe("real network Redis and SQL music recovery", () => {
	let f: Awaited<ReturnType<typeof createFixture>>;
	let reader: ReturnType<typeof redisClient.duplicate>;
	const activeRooms: Room[] = [];
	const keys: string[] = [];
	beforeAll(async () => {
		const target = targets();
		// Fast failure before the production client's reconnect policy is involved.
		const probe = redis.createClient({
			url: target.redis,
			socket: { reconnectStrategy: false, connectTimeout: 3000 },
		});
		probe.on("error", () => undefined);
		try {
			await probe.connect();
			expect(await probe.ping()).toBe("PONG");
		} finally {
			if (probe.isOpen) {
				await probe.quit();
			}
		}
		conf.set("redis.url", target.redis);
		conf.set("redis.db", 15);
		await buildClients();
		reader = await createSubscriber();
		console.log(
			`Real Redis runtime: ${(await redisClient.info("server")).match(REDIS_VERSION)?.[1].trim()}`,
		);
	});
	afterAll(async () => {
		if (reader?.isOpen) {
			await reader.quit();
		}
		if (redisClient?.isOpen) {
			await redisClient.quit();
		}
	});
	beforeEach(async () => {
		f = await createFixture();
	});
	afterEach(async () => {
		for (const room of activeRooms.splice(0)) {
			room.throttledSync.cancel();
			room.saveStateToRedisDebounced.cancel();
		}
		// Delete only keys generated by this test; never FLUSHDB or scan an external database.
		for (const key of keys.splice(0)) {
			await redisClient.del(key);
		}
		await f?.cleanup();
	});
	const makeRoom = (
		options: ConstructorParameters<typeof Room>[0],
		connection = f.connection,
		catalogue = f.catalogue,
	) => {
		const room = new Room(options, {
			catalogue,
			store: new SqlMusicRoomStore(() => connection),
		});
		room.throttledSync.cancel();
		// Keep the real Room publication path, but prevent an unrelated timer from writing settings.
		room.throttledSync = Object.assign(() => undefined, {
			cancel: () => undefined,
		}) as unknown as typeof room.throttledSync;
		activeRooms.push(room);
		return room;
	};

	it("roundtrips real Room snapshots across Redis clients, uses SQL without Redis, and never double credits", async () => {
		const name = `music-test-${targets().runId}`;
		const key = `room:${name}`;
		expect(await redisClient.exists(key)).toBe(0);
		// Claim this exact key atomically before allowing teardown to delete it.
		expect(await redisClient.set(key, "synthetic-claim", { NX: true, EX: 300 })).toBe("OK");
		keys.push(key);
		const version = await f.connection.query<{ version: string }>("SELECT version()", {
			type: QueryTypes.SELECT,
		});
		console.log(`Real PostgreSQL runtime: ${version[0].version}`);
		for (const id of ["redis-a", "redis-b", "redis-c"]) {
			await f.catalogue.addLibraryTrack(1, { reference: reference(id) });
		}
		const room = makeRoom({ name, queueMode: QueueMode.Music });
		const user = new RoomUser("synthetic-tab", "synthetic-token");
		user.user_id = 1;
		room.realusers.push(user);
		await room.musicEngine.refresh(true);
		await room.dequeueNext();
		await room.play();
		const before = room.musicState!;
		expect(before.history.events).toHaveLength(1);
		// Exercise Room's production save method and debounce flush, not just a synthetic SET.
		room.saveStateToRedisDebounced();
		await room.saveStateToRedisDebounced.flush();
		const stored = await reader.get(key);
		expect(stored).toBeTruthy();
		expect(await reader.ttl(key)).toBeGreaterThan(0);
		const raw = JSON.parse(stored!) as RoomStateFromRedis;
		expect(raw.musicState).toEqual(JSON.parse(JSON.stringify(before)));
		expect(raw).not.toHaveProperty("music");
		const sync = JSON.parse(room.serializeSyncableState());
		expect(sync.music.current.playbackId).toBe(before.current!.playbackId);
		expect(sync).not.toHaveProperty("musicState");
		expect(sync.music).not.toHaveProperty("history");
		expect(sync.music).not.toHaveProperty("candidates");
		const peer = f.peer();
		const restored = makeRoom(redisStateToState(raw), peer.connection, peer.catalogue);
		await restored.initializeMusic();
		await restored.play();
		expect(restored.musicState!.history).toEqual(before.history);
		expect(restored.musicState!.current!.playbackId).toBe(before.current!.playbackId);
		await redisClient.del(key);
		expect(await reader.get(key)).toBeNull();
		const fallback = makeRoom(
			{ name, queueMode: QueueMode.Music },
			peer.connection,
			peer.catalogue,
		);
		await fallback.initializeMusic();
		await fallback.play();
		expect(fallback.musicState!.history).toEqual(before.history);
		expect(fallback.musicState!.sessionId).toBe(before.sessionId);
		expect(await musicRoomModels(peer.connection).Event.count()).toBe(1);
		expect((await musicRoomModels(peer.connection).Score.findOne())!.get().plays).toBe(1);
	});
});
